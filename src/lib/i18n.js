export const supportedLocales = ['zh', 'en'];
export const defaultLocale = 'zh';

export function detectLocale(acceptLanguage = '') {
    const lowered = acceptLanguage.toLowerCase();
    if (!lowered) return defaultLocale;

    const choices = lowered
        .split(',')
        .map((part) => part.trim().split(';')[0])
        .filter(Boolean);

    const prefersChinese = choices.some((locale) => locale === 'zh' || locale.startsWith('zh-'));
    if (prefersChinese) return 'zh';

    const prefersEnglish = choices.some((locale) => locale === 'en' || locale.startsWith('en-'));
    if (prefersEnglish) return 'en';

    return defaultLocale;
}

export function getPathValue(source, path) {
    return path.split('.').reduce((value, key) => value?.[key], source);
}

export function formatMessage(template, values = {}) {
    if (typeof template !== 'string') return template;

    return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
        const value = values[key];
        return value === undefined || value === null ? '' : String(value);
    });
}

